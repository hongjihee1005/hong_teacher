"""두음법칙(첫소리 ㄹ·ㄴ 바꾸기) — words.py·gen.py가 같이 씀"""
DU = {'라': '나', '래': '내', '로': '노', '뢰': '뇌', '루': '누', '르': '느', '랑': '낭', '량': '양', '려': '여', '례': '예', '료': '요', '류': '유', '리': '이', '랴': '야',
      '녀': '여', '뇨': '요', '뉴': '유', '니': '이', '력': '역', '련': '연', '렬': '열', '렴': '염', '렵': '엽', '령': '영', '록': '녹', '론': '논', '롱': '농', '륙': '육', '륜': '윤',
      '률': '율', '륭': '융', '름': '름', '릉': '능', '린': '인', '림': '임', '립': '입', '락': '낙', '란': '난', '람': '남', '랍': '납', '략': '약', '랭': '냉', '년': '연', '념': '염', '녕': '영', '닉': '익', '닐': '일'}
def dueum(syl):
    """첫소리 두음법칙: 리→이, 녀→여, 라→나 …(한글 음절 단위)"""
    if syl in DU: return DU[syl]
    c = ord(syl) - 0xAC00
    if not 0 <= c < 11172: return syl
    ini, med, fin = c // 588, (c % 588) // 28, c % 28
    if ini == 5:   # ㄹ
        ini = 11 if med in (2, 6, 7, 12, 17, 20) else 2   # ㅑㅕㅖㅛㅠㅣ → ㅇ, 그 밖 → ㄴ
    elif ini == 2 and med in (2, 6, 7, 12, 17, 20): ini = 11
    return chr(0xAC00 + ini * 588 + med * 28 + fin)
