def grid(rows): return [[1 if ch == '#' else 0 for ch in r] for r in rows]

def gen():
    data = {}
    for lv, items in PICS.items():
        out = []
        for nm, rows in items:
            G = grid(rows); H, W = len(G), len(G[0])
            rc = [clues(r) for r in G]; cc = [clues([G[r][c] for r in range(H)]) for c in range(W)]
            sol, rounds = solve(rc, cc)
            out.append({'nm': nm, 'w': W, 'h': H, 'rc': rc, 'cc': cc, 's': [''.join('1' if v else '0' for v in r) for r in G], 'k': rounds})
        data[lv] = sorted(out, key=lambda p: (p['k'], sum(r.count('1') for r in p['s'])))
    return data

def check(data):
    bad = []
    size = {'easy': 5, 'normal': 10, 'hard': 15}
    for lv, items in PICS.items():
        for nm, rows in items:
            if len(rows) != size[lv] or any(len(r) != size[lv] or set(r) - set('#.') for r in rows): bad.append(f'{lv} {nm}: 크기·글자가 틀림'); continue
            G = grid(rows); H, W = len(G), len(G[0])
            rc = [clues(r) for r in G]; cc = [clues([G[r][c] for r in range(H)]) for c in range(W)]
            sol, _ = solve(rc, cc)
            if sol != G: bad.append(f'{lv} {nm}: 줄 논리만으로는 풀리지 않음(찍어야 하거나 답이 여럿)')
    for lv, ps in data.items():
        names = [p['nm'] for p in ps]
        if len(set(names)) != len(names): bad.append(f'{lv}: 같은 이름')
        pics = [tuple(p['s']) for p in ps]
        if len(set(pics)) != len(pics): bad.append(f'{lv}: 같은 그림')
    return bad

if __name__ == '__main__':
    out = HERE / 'data' / 'nonogram.json'
    data = gen(); bad = check(data)
    if sys.argv[1:2] == ['check']:
        if not bad and json.loads(out.read_text()) != json.loads(json.dumps(data)): bad.append('data/nonogram.json이 그림 원본과 다름 — python3 gen_nonogram.py로 다시 만드세요')
        print('\n'.join(bad) or '네모 로직 점검 통과'); sys.exit(1 if bad else 0)
    if bad: print('\n'.join(bad)); sys.exit(1)
    out.write_text(json.dumps(data, ensure_ascii=False, separators=(',', ':')))
