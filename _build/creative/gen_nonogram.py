def clues(line):
    out, run = [], 0
    for v in line:
        if v: run += 1
        elif run: out.append(run); run = 0
    if run: out.append(run)
    return out

def line_solve(cl, cur):
    """cur: 칸마다 1(칠함)·0(빔)·None(모름). 이 줄에 맞는 놓기를 모두 늘어놓아 칸마다 (칠할 수 있나, 비울 수 있나). 맞는 놓기가 없으면 None"""
    n, k = len(cur), len(cl); can1 = [False] * n; can0 = [False] * n; any_ok = [False]
    def rec(i, j, line):
        if j == k:
            full = line + [0] * (n - i)
            if all(c is None or c == v for c, v in zip(cur, full)):
                any_ok[0] = True
                for x, v in enumerate(full):
                    if v: can1[x] = True
                    else: can0[x] = True
            return
        rest = sum(cl[j + 1:]) + (k - j - 1)
        for s in range(i, n - cl[j] - rest + 1):
            seg = [0] * (s - i) + [1] * cl[j] + ([0] if s + cl[j] < n else [])
            if all(cur[x] is None or cur[x] == v for x, v in zip(range(i, i + len(seg)), seg)):
                rec(i + len(seg), j + 1, line + seg)
    rec(0, 0, [])
    return (can1, can0) if any_ok[0] else None

def solve(rc, cc):
    R, C = len(rc), len(cc); g = [[None] * C for _ in range(R)]; changed = True; rounds = 0
    while changed:
        changed = False; rounds += 1
        for r in range(R):
            res = line_solve(tuple(rc[r]), tuple(g[r]))
            if res is None: return None, rounds
            for c in range(C):
                if g[r][c] is None and res[0][c] != res[1][c]: g[r][c] = 1 if res[0][c] else 0; changed = True
        for c in range(C):
            res = line_solve(tuple(cc[c]), tuple(g[r][c] for r in range(R)))
            if res is None: return None, rounds
            for r in range(R):
                if g[r][c] is None and res[0][r] != res[1][r]: g[r][c] = 1 if res[0][r] else 0; changed = True
    if any(v is None for row in g for v in row): return None, rounds
    return g, rounds

