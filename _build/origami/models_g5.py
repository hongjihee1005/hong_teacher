def iso(x, y, z, k=46, cx=120, cy=150):
    return (cx + (x - y) * .866 * k, cy + (x + y) * .5 * k - z * k)
def face(ps, f='c', k=46, cy=150): return P([iso(*p, k=k, cy=cy) for p in ps], f)
H = 1                                          # 벽 높이 = 바닥 한 변의 1/2 (상자 안쪽 깊이)
def box(front=True, k=46, cy=150):
    """입체 상자: 바닥 → 안쪽 벽(뒤) → 바깥 벽(앞). front=False면 앞쪽(x=1) 벽은 아직 펼친 채"""
    out = [face([(-1, -1, 0), (1, -1, 0), (1, 1, 0), (-1, 1, 0)], 'w', k, cy),
           face([(-1, -1, 0), (-1, 1, 0), (-1, 1, H), (-1, -1, H)], 'c2', k, cy),      # 뒤 끝 벽(x=-1)
           face([(-1, -1, 0), (1, -1, 0), (1, -1, H), (-1, -1, H)], 'c', k, cy)]       # 오른쪽 옆벽(y=-1)
    if front: out += [face([(1, -1, 0), (1, 1, 0), (1, 1, H), (1, -1, H)], 'c2', k, cy)]
    else: out += [face([(1, -1, 0), (2, -1, 0), (2.2, 0, 0), (2, 1, 0), (1, 1, 0)], 'w', k, cy), face([(1, -1, 0), (1, 1, 0), (2.2, 0, 0)], 'c', k, cy)]
    out += [face([(-1, 1, 0), (1, 1, 0), (1, 1, H), (-1, 1, H)], 'c', k, cy)]           # 왼쪽 옆벽(y=1)
    return out
