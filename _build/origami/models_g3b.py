def keep_side(poly, a, b, keep):
    """직선 ab로 잘라 keep 점 쪽만 남기기(산 접기로 뒤로 넘어간 부분은 안 보임)"""
    l, r = split(poly, a, b)
    return l if side(keep, a, b) >= 0 else r

