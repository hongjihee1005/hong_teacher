SW = {'w': 'c2', 'w2': 'c2', 'c': 'w', 'c2': 'w'}
def FL(layers, a, b, keep):
    """여러 겹을 한꺼번에 접기 → 남는 겹(그대로) + 넘어간 겹(뒤집혀 위로, 겉과 속이 바뀜)"""
    stay, mov = [], []
    for poly, f in layers:
        l, r = split(poly, a, b)
        st, mv = (l, r) if side(keep, a, b) >= 0 else (r, l)
        if len(st) >= 3: stay.append((st, f))
        if len(mv) >= 3: mov.append((Rs(mv, a, b), SW.get(f, f)))
    return stay + mov[::-1]
def PL(layers): return [P(p, f) for p, f in layers]
def ray(o, deg, r=400):
    t = math.radians(deg); return (o[0] + r * math.cos(t), o[1] + r * math.sin(t))

