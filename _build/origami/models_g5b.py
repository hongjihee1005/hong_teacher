def blintz(q, f='c'):
    """네 꼭짓점을 가운데로 모은 모양: (가운데 이은 네모, 접힌 세모 4장)"""
    c = (sum(p[0] for p in q) / 4, sum(p[1] for p in q) / 4)
    m = [mid(q[i], q[(i + 1) % 4]) for i in range(4)]
    return m, [P([m[i - 1], m[i], c], f) for i in range(4)]

def to_c(q, k=.1, e=.78, bend=.25):
    """꼭짓점마다 가운데로 가는 화살표"""
    c = (sum(p[0] for p in q) / 4, sum(p[1] for p in q) / 4)
    return [A(lerp(p, c, k), lerp(p, c, e), bend) for p in q]

