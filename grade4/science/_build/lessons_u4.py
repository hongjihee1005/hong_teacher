def mold(cx, cy, r, c='#7FA383'):  # 솜털 같은 곰팡이 자국(이름·답은 쓰지 않음)
    dots = ''.join(f'<circle cx="{cx + dx * r / 10:.1f}" cy="{cy + dy * r / 10:.1f}" r="{max(.7, r / 9):.1f}" fill="#3F5A48"/>'
                   for dx, dy in [(-4, -3), (3, -5), (5, 2), (-2, 4), (0, 0), (-6, 1)])
    return f'<circle cx="{cx}" cy="{cy}" r="{r + 2}" fill="#F4F6F0" opacity=".9"/><circle cx="{cx}" cy="{cy}" r="{r}" fill="{c}"/>' + dots


def cilia(cx, cy, rx, ry, n=18, L=6, c='#4F8F80'):  # 둘레의 가는 털
    d = []
    for i in range(n):
        a = math.pi * 2 * i / n
        x, y = cx + rx * math.cos(a), cy + ry * math.sin(a)
        d.append(f'M{x:.1f} {y:.1f} l{L * math.cos(a):.1f} {L * math.sin(a) - 2:.1f}')
    return f'<path d="{" ".join(d)}" stroke="{c}" stroke-width="1.3" fill="none"/>'


