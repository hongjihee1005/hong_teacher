def comp(cx, cy, r=12, needle=None):
    """나침반(바늘 없음이 기본). needle=각도(도, 0=위쪽)이면 빨강/흰 바늘을 그림."""
    s = (f'<circle cx="{cx}" cy="{cy}" r="{r}" fill="#FFFDF5" stroke="#5A5A5A" stroke-width="1.8"/>'
         f'<circle cx="{cx}" cy="{cy}" r="{r - 3}" fill="none" stroke="#C9C2B0" stroke-width="0.8"/>')
    if needle is not None:
        L = r - 4
        s += (f'<g transform="rotate({needle} {cx} {cy})"><path d="M{cx} {cy - L} L{cx + r * .22} {cy} L{cx - r * .22} {cy} Z" fill="#E05A4F"/>'
              f'<path d="M{cx} {cy + L} L{cx + r * .22} {cy} L{cx - r * .22} {cy} Z" fill="#E9E9E9" stroke="#999" stroke-width=".6"/></g>'
              f'<circle cx="{cx}" cy="{cy}" r="1.6" fill="#333"/>')
    return s


